#!/usr/bin/env python3
"""Build matte split-flap cards and packed, antialiased DejaVu numeral masks."""
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
WIDTH, HEIGHT, SCALE = 135, 240, 3
GLYPH_W, GLYPH_H = 97, 154


def background():
    image = Image.new('RGB',(WIDTH*SCALE,HEIGHT*SCALE),(3,4,6))
    draw = ImageDraw.Draw(image)

    def rect(bounds, color, radius=0, outline=None):
        bounds = tuple(round(c*SCALE) for c in bounds)
        draw.rounded_rectangle(bounds,radius=round(radius*SCALE),fill=color,
                               outline=outline,width=SCALE)

    rect((5,27,130,217),(1,2,3),10)
    rect((6,26,128,214),(16,19,23),9,outline=(40,44,50))
    rect((8,29,126,211),(9,11,15),7)
    rect((9,30,125,119),(33,37,44),6)
    rect((9,121,125,210),(27,30,36),6)
    # Soft satin gradients; the background itself contains no numerals.
    for y in range(37,115):
        c = (y-37)/78
        rect((10,y,124,y+1),tuple(round(a+(b-a)*c) for a,b in
                                zip((34,38,45),(26,29,35))))
    for y in range(126,204):
        c = (y-126)/78
        rect((10,y,124,y+1),tuple(round(a+(b-a)*c) for a,b in
                                zip((23,26,32),(32,35,41))))
    rect((15,30,119,30.4),(69,73,80))
    rect((15,209,119,209.4),(47,50,56))
    rect((9,118,125,121),(2,3,5))
    rect((12,122,122,122.4),(53,56,61))
    for x in (6,122):
        rect((x,114,x+6,126),(8,10,13),2,outline=(47,51,58))
        rect((x+1,115,x+5,117),(101,105,111),1)
        rect((x+2,119,x+4,124),(27,30,35),1)
    image = image.resize((WIDTH,HEIGHT),Image.Resampling.LANCZOS)
    # A small molded screw in each corner gives the face a physical frame.
    draw = ImageDraw.Draw(image)
    for x in (11,123):
        for y in (20,220):
            draw.ellipse((x-1,y-1,x+1,y+1),fill=(30,33,39))
            draw.point((x,y),fill=(9,11,14))
    image = image.quantize(colors=32,method=Image.Quantize.MEDIANCUT).convert('RGB')
    colors = sorted(set(image.getdata()))
    lookup = {color:index for index,color in enumerate(colors)}
    indices = [lookup[color] for color in image.getdata()]
    palette = [((r&248)<<8)|((g&252)<<3)|(b>>3) for r,g,b in colors]
    return indices,palette


def glyphs():
    font = ImageFont.truetype('/usr/share/fonts/truetype/dejavu/DejaVuSansCondensed-Bold.ttf',210*SCALE)
    boxes = [font.getbbox(str(n)) for n in range(10)]
    left,top = min(b[0] for b in boxes),min(b[1] for b in boxes)
    right,bottom = max(b[2] for b in boxes),max(b[3] for b in boxes)
    result = []
    for digit in range(10):
        image = Image.new('L',(right-left,bottom-top))
        ImageDraw.Draw(image).text((-left,-top),str(digit),font=font,fill=255)
        image = image.resize((GLYPH_W,GLYPH_H),Image.Resampling.LANCZOS)
        pixels = [round(p*15/255) for p in image.getdata()]
        result += [(pixels[n]<<4)|(pixels[n+1] if n+1<len(pixels) else 0)
                   for n in range(0,len(pixels),2)]
    return result


def main():
    base,palette = background()
    header = '// Generated by tools/generate_flip.py; DejaVu Sans: see FONT-LICENSE.txt.\n'
    header += '#pragma once\n#include <stdint.h>\n#ifdef ARDUINO\n#include <Arduino.h>\n#else\n#ifndef PROGMEM\n#define PROGMEM\n#endif\n#endif\n\n'
    header += f'static const unsigned kFlipColors = {len(palette)};\n'
    def array(name,ctype,values):
        nonlocal header
        header += f'static const {ctype} {name}[{len(values)}] PROGMEM = {{\n'
        header += '\n'.join('  '+','.join(str(v) for v in values[n:n+24])+','
                            for n in range(0,len(values),24))
        header += '\n};\n\n'
    array('kFlipBackground','uint8_t',base)
    array('kFlipPalette','uint16_t',palette)
    array('kFlipGlyphs','uint8_t',glyphs())
    path = ROOT/'src/flip_assets.h'
    path.write_text(header.rstrip()+'\n')
    print('Generated',path,flush=True)


if __name__ == '__main__':
    main()
