def field(path):
    width, height = GW*SCALE, GH*SCALE
    mask = Image.new('L',(width,height))
    draw = ImageDraw.Draw(mask)
    for line in polylines(path):
        draw.line([(round(x*GW/100*SCALE),round(y*GH/160*SCALE)) for x,y in line],
                  fill=255,width=1)
    raw = mask.tobytes()
    rows = [distance_1d([0 if raw[y*width+x] else 10000000 for x in range(width)])
            for y in range(height)]
    output = [0]*(GW*GH)
    for x in range(GW):
        column = distance_1d([row[x*SCALE+1] for row in rows])
        for y in range(GH):
            distance = math.sqrt(column[y*SCALE+1])/SCALE
            output[y*GW+x] = min(range(16),key=lambda n:abs(DISTANCES[n]-distance))
    return [(output[n]<<4)|output[n+1] for n in range(0,len(output),2)]


def background():
    image = Image.new('RGB',(135,240))
    pixels = image.load()
    for y in range(240):
        for x in range(135):
            center = math.exp(-((x-67)/62)**2-((y-120)/105)**2)
            nebula = math.exp(-((x-28)/52)**2-((y-162)/85)**2)
            pixels[x,y] = (round(2+3*center+4*nebula),round(4+6*center),round(9+12*center+7*nebula))
    draw = ImageDraw.Draw(image)
    # Recessed instrument rails, fine measurement ticks and a quiet title.
    for x in (5,129):
        draw.line((x,49,x,192),fill=(12,27,41))
        for y in range(56,193,8):
            inward = 3 if y%24 == 8 else 1
            draw.line((x,y,x+(inward if x==5 else -inward),y),fill=(22,47,61))
    draw.line((29,23,105,23),fill=(16,42,57))
    draw.line((29,216,105,216),fill=(16,42,57))
    font = ImageFont.truetype('/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf',7)
    x = 47
    for letter in 'ORBIT':
        draw.text((x,11),letter,font=font,fill=(65,116,139))
        x += 9
    for n in range(15):
        x = 32+n*5
        draw.line((x,223,x,226+(n%7==0)*2),fill=(21,48,64))
    # Ordered RGB565 dithering preserves the dark gradients on the actual TFT.
    bayer = ((0,8,2,10),(12,4,14,6),(3,11,1,9),(15,7,13,5))
    result = []
    for n,(r,g,b) in enumerate(image.getdata()):
        threshold = bayer[(n//135)%4][n%4]/16
        result.append((min(31,int(r*31/255+threshold))<<11)|
                      (min(63,int(g*63/255+threshold))<<5)|min(31,int(b*31/255+threshold)))
    return result


def main():
    header = '// Generated by tools/generate_orbit.py. Original numeral geometry.\n'
    header += '#pragma once\n#include <stdint.h>\n#ifdef ARDUINO\n#include <Arduino.h>\n#else\n#ifndef PROGMEM\n#define PROGMEM\n#endif\n#endif\n\n'
    for name,ctype,values in (('kOrbitBackground','uint16_t',background()),
                              ('kOrbitGlyphs','uint8_t',[v for path in PATHS for v in field(path)])):
        header += f'static const {ctype} {name}[{len(values)}] PROGMEM = {{\n'
        header += '\n'.join('  '+','.join(map(str,values[n:n+24]))+','
                            for n in range(0,len(values),24))+'\n};\n'
    (ROOT/'src/orbit_assets.h').write_text(header)
    print('Generated Orbit background and ten original distance-field numerals.')


if __name__ == '__main__':
    main()
