#!/usr/bin/env python3
"""Generate small anti-aliased TFT_eSPI VLW fonts from DejaVu Sans.

The generated header is committed; Pillow and the TTF are only needed to rebuild
it. The VLW layout follows TFT_eSPI/Extensions/Smooth_font.cpp.
"""
import argparse
from pathlib import Path
import struct

from PIL import Image, ImageDraw, ImageFont


def vlw(path, size, chars):
    font = ImageFont.truetype(str(path), size)
    glyphs, bitmaps = [], []
    ascent = descent = 0
    for char in chars:
        left, top, right, bottom = font.getbbox(char, anchor="ls")
        width, height = right - left, bottom - top
        image = Image.new("L", (width, height))
        ImageDraw.Draw(image).text((-left, -top), char, font=font, fill=255, anchor="ls")
        glyphs.append((ord(char), height, width, round(font.getlength(char)), -top, left, 0))
        bitmaps.append(image.tobytes())
        ascent, descent = max(ascent, -top), max(descent, bottom)
    data = struct.pack(">6I", len(glyphs), 11, size, 0, ascent, descent)
    data += b"".join(struct.pack(">7i", *glyph) for glyph in glyphs)
    return data + b"".join(bitmaps)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--font", type=Path, default=Path("/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"))
    parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parents[1] / "src/monitor_fonts.h")
    args = parser.parse_args()
    text = "// Generated by tools/generate_fonts.py. DejaVu Sans: see FONT-LICENSE.txt.\n#pragma once\n#include <Arduino.h>\n\n"
    for name, size, chars in (("kLabelFont", 12, "".join(chr(n) for n in range(33, 127)) + "°"),
                              ("kRateFont", 24, "0123456789.-"),
                              ("kValueFont", 38, "0123456789.-")):
        data = vlw(args.font, size, chars)
        text += f"static const uint8_t {name}[] PROGMEM = {{\n"
        text += "\n".join("  " + ",".join(f"0x{b:02x}" for b in data[i:i+24]) + "," for i in range(0, len(data), 24))
        text += "\n};\n\n"
        print(name, len(data), "bytes")
    args.output.write_text(text.rstrip()+'\n')


if __name__ == "__main__":
    main()
